"""Small deterministic Fabric 1.21.1 prototype generator.

No generated executable is run and no downloaded script is evaluated.
The output is SOURCE ONLY until a separate verified Gradle build occurs.
"""
from __future__ import annotations
import hashlib
import json
import os
import struct
import zlib
from pathlib import Path
from .config import PROFILE
from .spec import Spec
from .validation import InputError, safe_inside, ensure_new_directory


def placeholder_png(name: str, size: int = 16) -> bytes:
    """Deterministic pixel art placeholder PNG using only Python stdlib."""
    digest = hashlib.sha256(name.encode()).digest()
    main = (40 + digest[0] % 170, 40 + digest[1] % 170, 40 + digest[2] % 170)
    outline = tuple(max(0, c - 50) for c in main)
    shine = tuple(min(255, c + 50) for c in main)
    rows = []
    for y in range(size):
        pixels = []
        for x in range(size):
            edge = x in (0, size - 1) or y in (0, size - 1)
            alternate = ((x // 4) + (y // 4)) % 2 == 0
            color = outline if edge else shine if alternate else main
            pixels.extend([*color, 255])
        rows.append(b"\x00" + bytes(pixels))
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(b"".join(rows))) + chunk(b"IEND", b"")


def generate(spec: Spec, directory: Path) -> dict:
    """Write an entirely new workspace with a generated/UNVERIFIED status."""
    if spec.questions:
        raise InputError("Cannot generate until blocking questions are resolved: " + "; ".join(spec.questions))
    if not spec.features:
        raise InputError("At least one deterministic item/block feature required")
    if spec.profile != PROFILE["id"]:
        raise InputError("Unsupported target profile")
    directory = Path(directory).expanduser()
    ensure_new_directory(directory)
    directory.mkdir(parents=True, exist_ok=True)
    written: dict[str, str] = {}

    def put(relative: str, content: str | bytes) -> None:
        target = safe_inside(directory, relative)
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            raise InputError("No overwrite permitted: " + relative)
        raw = content.encode("utf-8") if isinstance(content, str) else content
        with target.open("xb") as f:
            f.write(raw)
        written[relative] = hashlib.sha256(raw).hexdigest()

    p = PROFILE
    put("settings.gradle", f"""pluginManagement {{\n    repositories {{ maven {{ url = 'https://maven.fabricmc.net/' }}; gradlePluginPortal(); mavenCentral() }}\n}}\nrootProject.name = '{spec.mod_id}'\n""")
    put("gradle.properties", f"""org.gradle.jvmargs=-Xmx2G\norg.gradle.parallel=true\nminecraft_version={p['minecraft']}\nyarn_mappings={p['yarn']}\nloader_version={p['fabric_loader']}\nfabric_version={p['fabric_api']}\nmod_version=1.0.0\nmaven_group={spec.package}\narchives_base_name={spec.mod_id}\n""")
    put("build.gradle", f"""plugins {{\n    id 'fabric-loom' version '{p['loom']}'\n}}\n\nversion = project.mod_version\ngroup = project.maven_group\nbase {{ archivesName = project.archives_base_name }}\n\ndependencies {{\n    minecraft 'com.mojang:minecraft:' + project.minecraft_version\n    mappings 'net.fabricmc:yarn:' + project.yarn_mappings + ':v2'\n    modImplementation 'net.fabricmc:fabric-loader:' + project.loader_version\n    modImplementation 'net.fabricmc.fabric-api:fabric-api:' + project.fabric_version\n}}\n\nprocessResources {{\n    inputs.property 'version', project.version\n    filesMatching('fabric.mod.json') {{ expand 'version': project.version }}\n}}\n\ntasks.withType(JavaCompile).configureEach {{\n    it.options.release = {p['java_major']}\n    it.options.encoding = 'UTF-8'\n}}\njava {{ sourceCompatibility = JavaVersion.VERSION_{p['java_major']}; targetCompatibility = JavaVersion.VERSION_{p['java_major']} }}\n""")
    # This generated workspace intentionally omits third-party Gradle wrapper binaries.
    put("gradle/wrapper/gradle-wrapper.properties", f"distributionUrl=https\\://services.gradle.org/distributions/gradle-{p['gradle']}-bin.zip\n")
    put(".gitignore", ".gradle/\nbuild/\nrun/\n.idea/\n*.class\n")
    put("README.md", f"""# {spec.name}\n\nGenerated by Minecraft Mod Orchestra. **SOURCE GENERATED — NOT BUILD VERIFIED.**\n\nMinecraft {p['minecraft']} / Fabric Loader {p['fabric_loader']} / Java {p['java_major']}.\n\n### Build\n\n1. Review generated source and dependencies.\n2. Install JDK {p['java_major']} and a trusted Gradle distribution (Gradle {p['gradle']}).\n3. In this directory run `gradle wrapper --gradle-version {p['gradle']}` (produces verified official wrapper files locally).\n4. Run `./gradlew build` on Linux/macOS or `gradlew.bat build` on Windows.\n5. Review `build/libs/`. Do not call the mod tested until the game loads and the content is exercised.\n\nNo existing Minecraft launcher installation is needed to compile, but network access is needed on initial Gradle resolution.\n\nYour idea: {spec.idea}\n""")
    put("fabric-profile.lock.json", json.dumps(p, indent=2) + "\n")
    java_dir = "src/main/java/" + spec.package.replace(".", "/")
    lines = [
        f"package {spec.package};", "", "import net.fabricmc.api.ModInitializer;",
        "import net.fabricmc.fabric.api.itemgroup.v1.ItemGroupEvents;",
        "import net.minecraft.block.AbstractBlock;", "import net.minecraft.block.Block;",
        "import net.minecraft.item.BlockItem;", "import net.minecraft.item.Item;",
        "import net.minecraft.item.ItemGroups;", "import net.minecraft.registry.Registries;",
        "import net.minecraft.registry.Registry;", "import net.minecraft.util.Identifier;",
        "", f"public class ModMain implements ModInitializer {{", f'    public static final String MOD_ID = "{spec.mod_id}";',
    ]
    for feature in spec.features:
        varname = feature.identifier.upper()
        if feature.kind == "item":
            lines.append(f"    public static final Item {varname} = Registry.register(Registries.ITEM, Identifier.of(MOD_ID, \"{feature.identifier}\"), new Item(new Item.Settings()));")
        else:
            lines.append(f"    public static final Block {varname} = Registry.register(Registries.BLOCK, Identifier.of(MOD_ID, \"{feature.identifier}\"), new Block(AbstractBlock.Settings.create().strength(3.0F)));")
            lines.append(f"    public static final Item {varname}_ITEM = Registry.register(Registries.ITEM, Identifier.of(MOD_ID, \"{feature.identifier}\"), new BlockItem({varname}, new Item.Settings()));")
    lines.append("    @Override public void onInitialize() {")
    for feature in spec.features:
        group = "BUILDING_BLOCKS" if feature.kind == "block" else "INGREDIENTS"
        suffix = "_ITEM" if feature.kind == "block" else ""
        lines.append(f"        ItemGroupEvents.modifyEntriesEvent(ItemGroups.{group}).register(entries -> entries.add({feature.identifier.upper()}{suffix}));")
    lines += ["    }", "}"]
    put(f"{java_dir}/ModMain.java", "\n".join(lines) + "\n")
    put("src/main/resources/fabric.mod.json", json.dumps({
        "schemaVersion": 1, "id": spec.mod_id, "version": "${version}", "name": spec.name,
        "description": "Generated Fabric starter from a user idea", "environment": "*",
        "entrypoints": {"main": [spec.package + ".ModMain"]},
        "depends": {"fabricloader": ">=0.16.14", "minecraft": "~1.21.1", "java": ">=21", "fabric-api": "*"},
        "license": "ARR",
    }, indent=2) + "\n")
    res = f"src/main/resources/assets/{spec.mod_id}"
    put("src/main/resources/pack.mcmeta", json.dumps({"pack": {"pack_format": 34, "description": spec.name + " assets"}}, indent=2) + "\n")
    lang = {}
    for feature in spec.features:
        key = feature.identifier
        lang[f"{'block' if feature.kind == 'block' else 'item'}.{spec.mod_id}.{key}"] = feature.label
        if feature.kind == "item":
            put(f"{res}/models/item/{key}.json", json.dumps({"parent": "item/generated", "textures": {"layer0": f"{spec.mod_id}:item/{key}"}}, indent=2) + "\n")
            put(f"{res}/textures/item/{key}.png", placeholder_png(spec.mod_id + "/" + key))
        else:
            put(f"{res}/blockstates/{key}.json", json.dumps({"variants": {"": {"model": f"{spec.mod_id}:block/{key}"}}}, indent=2) + "\n")
            put(f"{res}/models/block/{key}.json", json.dumps({"parent": "block/cube_all", "textures": {"all": f"{spec.mod_id}:block/{key}"}}, indent=2) + "\n")
            put(f"{res}/models/item/{key}.json", json.dumps({"parent": f"{spec.mod_id}:block/{key}"}, indent=2) + "\n")
            put(f"{res}/textures/block/{key}.png", placeholder_png(spec.mod_id + "/" + key))
            put(f"src/main/resources/data/{spec.mod_id}/loot_tables/blocks/{key}.json", json.dumps({"type": "minecraft:block", "pools": [{"rolls": 1, "entries": [{"type": "minecraft:item", "name": f"{spec.mod_id}:{key}"}], "conditions": [{"condition": "minecraft:survives_explosion"}]}]}, indent=2) + "\n")
    put(f"{res}/lang/en_us.json", json.dumps(lang, indent=2, sort_keys=True) + "\n")
    manifest = {"generator": "mod-orchestra 0.1.0", "status": "GENERATED_UNVERIFIED", "profile": p["id"], "files": written.copy(), "build_verified": False, "runtime_verified": False}
    put(".mod-orchestra/generation-manifest.json", json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return {"path": str(directory), "files": len(written), "status": "GENERATED_UNVERIFIED", "manifest": str(directory / ".mod-orchestra/generation-manifest.json")}


def validate_generated(path: Path) -> dict:
    manifest_file = path / ".mod-orchestra/generation-manifest.json"
    manifest = json.loads(manifest_file.read_text(encoding="utf8"))
    problems = []
    for relative, expected in manifest["files"].items():
        file_path = safe_inside(path, relative)
        if not file_path.is_file():
            problems.append("MISSING: " + relative)
        elif hashlib.sha256(file_path.read_bytes()).hexdigest() != expected:
            problems.append("CHANGED: " + relative)
        if relative.endswith(".json") and file_path.is_file():
            try:
                json.loads(file_path.read_text(encoding="utf8"))
            except (ValueError, UnicodeDecodeError) as exc:
                problems.append("BAD JSON: " + relative + ": " + str(exc))
    return {"status": "PASS" if not problems else "FAIL", "checked": len(manifest["files"]), "problems": problems, "note": "Static generation-only check; not a Minecraft build or runtime test"}
